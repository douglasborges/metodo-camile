import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {reconcileImaSubjects} from '../src/ima-sc-curriculum-20261105.js';
import {reconcileCamileImaProgress,mergeCamileBackupSafely,imaGoalWeek,imaCurrentGoalIndex,imaMetaSnapshot,IMA_META_WEEKS} from '../src/ima-camile-progresso-metas-20261107.js';
import {validate} from '../src/core.js';
const copy=v=>JSON.parse(JSON.stringify(v));
const seed=()=>reconcileImaSubjects(copy(JSON.parse(fs.readFileSync(new URL('../data/initial-state.json',import.meta.url),'utf8'))));
const u=(s,sid,id)=>s.subjects.find(x=>x.id===sid).units.find(x=>x.id===id);
const add=(s,sid,id,date,activity,minutes,questions=0,correct=0)=>{s.sessions.push({id:'test'+s.sessions.length,subjectId:sid,unitId:id,date,activity,minutes,questions,correct,title:'Teste'});};
test('backup com 240min em disciplinas IMA é compatível com validação legada',()=>{
 const s=seed();assert.equal(s.subjects.find(x=>x.id==='rl-ima').slotMinutes,240);assert.equal(s.subjects.find(x=>x.id==='licita-ima').slotMinutes,240);
 assert.equal(validate(s),s);
});
test('importação preserva aulas reais, credita acentuação forte e não inventa conclusão parcial',()=>{
 const s=seed();const p=u(s,'port','port-u-1');
 add(s,'port','port-u-1','2026-10-02','theory',90);
 add(s,'port','port-u-1','2026-10-03','theory',90);
 add(s,'port','port-u-1','2026-10-05','battery',60,42,40);
 add(s,'port','port-u-1','2026-10-06','free',20,120,111);
 add(s,'port','port-u-3','2026-10-05','theory',85);
 add(s,'port','port-u-3','2026-10-07','theory',92);
 add(s,'port','port-u-3','2026-10-12','theory',90);
 add(s,'port','port-u-5','2026-10-13','theory',85);
 add(s,'port','port-u-5','2026-10-13','theory',80);
 add(s,'adm-publica','MARC_ADM-ADM-AP-01','2026-10-22','theory',140);
 s.subjects.find(x=>x.id==='dcon').units.find(x=>x.id==='dcon-u-1').theoryDone=true;
 const oldLen=s.sessions.length;
 const a=reconcileCamileImaProgress(s),b=reconcileCamileImaProgress(a);
 assert.equal(a.sessions.length,oldLen);assert.equal(JSON.stringify(a),JSON.stringify(b));
 assert.equal(p.theoryDone,false);
 assert.equal(u(a,'port','port-u-1').theoryDone,true);
 assert.equal(u(a,'port','port-u-1').batteryDone,true);
 assert.equal(u(a,'port','port-u-1').imaPriorLearning.questions,162);
 assert.equal(u(a,'port','port-u-3').theoryDone,false);
 assert.equal(u(a,'port','port-u-3').imaPriorLearning.theoryMinutes,267);
 assert.equal(u(a,'port','port-u-5').theoryDone,false);
 assert.equal(u(a,'adm-publica','MARC_ADM-ADM-AP-05').theoryDone,false);
 assert.equal(u(a,'dcon','NELMA-DCON-01').theoryDone,true);
 assert.equal(u(a,'dad','ima-tha-dad-08').theoryDone,false);
 assert.equal(a.imaProfile.phase,'FUNDAMENTACAO_DAD_DCON');
 assert.equal(a.settings.weeklyMinimum,1800);
 assert.equal(a.settings.weeklyTarget,1800);
 assert.equal(a.subjects.find(x=>x.id==='afo').units.filter(x=>!x.hiddenFromRoute).length>0,true);
});
test('despesa de estudo parcial não dá conclusão automática em outra fonte de AFO',()=>{
 const s=seed();u(s,'afo','PAC_AFO-AFO-VG').theoryDone=true;
 add(s,'afo','PAC_AFO-AFO-PRI','2026-10-22','theory',96);
 add(s,'afo','PAC_AFO-AFO-PRI','2026-10-27','theory',120);
 const a=reconcileCamileImaProgress(s);
 assert.equal(u(a,'afo','IMA-AFO-M01').theoryDone,false);
 assert.equal(u(a,'afo','IMA-AFO-M03').imaPriorLearning.theoryMinutes,216);
 assert.equal(u(a,'afo','IMA-AFO-M03').theoryDone,false);
});
test('mesclar backup não substitui sessões recentes nem duplica IDs',()=>{
 const local=seed();add(local,'port','port-u-2','2026-11-07','theory',60);
 const old=copy(local);old.sessions=[];add(old,'port','port-u-1','2026-10-02','theory',90);
 const a=mergeCamileBackupSafely(local,old),b=mergeCamileBackupSafely(a,old);
 assert.equal(a.sessions.length,2);assert.equal(b.sessions.length,2);
 assert.ok(a.sessions.some(x=>x.unitId==='port-u-2'));
 assert.ok(a.sessions.some(x=>x.unitId==='port-u-1'));
 assert.equal(local.sessions.length,1);
});
